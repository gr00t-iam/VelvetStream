class Worker(QObject):
    finished = Signal()
    error = Signal(str)
    log = Signal(str)
    result = Signal(object)
    state = Signal(str)
    progress = Signal(int)
    level = Signal(float)
    manual_required = Signal(object)
    recording_saved = Signal(object)

    def __init__(self, stop: threading.Event):
        super().__init__()
        self.stop = stop

    @Slot()
    def run(self):
        try:
            result = self.execute()
            if result is not None:
                self.result.emit(result)
        except Cancelled:
            self.log.emit("Operation cancelled")
        except Exception as exc:
            # Report failure while always completing the Qt worker lifecycle.
            self.error.emit(str(exc) or type(exc).__name__)
        finally:
            self.finished.emit()

    def execute(self):
        raise NotImplementedError("Worker subclasses implement execute")


